import type { NavTab } from '../components/Sidebar';

/**
 * Full-module idiot-proof manual for the Help Center.
 *
 * Every module of the app contributes one entry: what it can do (features)
 * and exactly how to click through it (flow). Content is written so a first
 * time user can follow it without any prior context — each flow step names
 * the concrete entry point, the action, and the visible result.
 */

export interface ManualFeature {
  /** Feature name, aligned with the actual UI wording. */
  name: string;
  /** One-sentence explanation of what it does for the user. */
  desc: string;
}

export interface ManualFlowStep {
  /** Short action name, e.g. '选择目标资产'. */
  name: string;
  /** Idiot-proof detail: where to click -> what you see -> next move. */
  doing: string;
}

export interface ManualModule {
  /** Stable id used for anchor refs and expand state. */
  id: string;
  /** Short badge shown before the title ('M1' / '工作台' ...). */
  badge: string;
  tab: NavTab;
  title: string;
  role: '通用' | '用户聚焦' | '管理员';
  /** Tone key shared with the HelpCenter TONES map. */
  tone: string;
  /** Icon key resolved through MANUAL_ICONS in HelpCenter. */
  icon: string;
  /** One-line positioning statement. */
  slogan: string;
  features: ManualFeature[];
  flow: ManualFlowStep[];
  tips?: string[];
}

